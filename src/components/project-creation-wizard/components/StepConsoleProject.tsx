import { useEffect, useMemo, useState } from 'react';
import { Loader2, Plus, X } from 'lucide-react';
import { Input } from '../../../shared/view/ui';
import { fetchConsoleProjects, createConsoleProject } from '../data/consoleApi';
import type { ConsoleProject, ConsoleProjectSelection } from '../types';

type Mode = 'pick' | 'create' | 'skip';

type StepConsoleProjectProps = {
  selection: ConsoleProjectSelection | null;
  isCreating: boolean;
  onSelectionChange: (selection: ConsoleProjectSelection | null) => void;
};

export default function StepConsoleProject({
  selection,
  isCreating,
  onSelectionChange,
}: StepConsoleProjectProps) {
  // Mode is derived from current selection on first mount, then user-controlled.
  const [mode, setMode] = useState<Mode>(() => {
    if (selection?.isNew) return 'create';
    if (selection?.id) return 'pick';
    return 'pick';
  });

  // Pick-mode state
  const [search, setSearch] = useState('');
  const [debouncedSearch, setDebouncedSearch] = useState('');
  const [projects, setProjects] = useState<ConsoleProject[]>([]);
  const [loadingList, setLoadingList] = useState(false);
  const [listError, setListError] = useState<string | null>(null);

  // Create-mode state
  const [newName, setNewName] = useState(selection?.isNew ? selection.name : '');
  const [newDescription, setNewDescription] = useState('');
  const [creating, setCreating] = useState(false);
  const [createError, setCreateError] = useState<string | null>(null);

  // Debounce search to avoid hammering the proxy
  useEffect(() => {
    const handle = setTimeout(() => setDebouncedSearch(search), 250);
    return () => clearTimeout(handle);
  }, [search]);

  // Load projects when in pick mode + search changes
  useEffect(() => {
    if (mode !== 'pick') return;
    let disposed = false;
    setLoadingList(true);
    setListError(null);
    fetchConsoleProjects(debouncedSearch)
      .then((rows) => {
        if (!disposed) setProjects(rows);
      })
      .catch((err: Error) => {
        if (!disposed) setListError(err.message || 'Failed to load Console projects');
      })
      .finally(() => {
        if (!disposed) setLoadingList(false);
      });
    return () => {
      disposed = true;
    };
  }, [mode, debouncedSearch]);

  const selectedProject = useMemo(
    () => (selection?.id ? projects.find((p) => p.id === selection.id) : null),
    [projects, selection],
  );

  const handlePick = (project: ConsoleProject) => {
    onSelectionChange({ id: project.id, name: project.name, isNew: false });
  };

  const handleCreate = async () => {
    const name = newName.trim();
    if (!name) {
      setCreateError('Project name is required');
      return;
    }
    setCreating(true);
    setCreateError(null);
    try {
      const created = await createConsoleProject({
        name,
        description: newDescription.trim(),
        type: 'dev',
      });
      onSelectionChange({ id: created.id, name: created.name, isNew: true });
    } catch (err) {
      setCreateError(err instanceof Error ? err.message : 'Failed to create project');
    } finally {
      setCreating(false);
    }
  };

  const handleSkip = () => {
    onSelectionChange(null);
    setMode('skip');
  };

  const switchMode = (next: Mode) => {
    if (isCreating) return;
    setMode(next);
    if (next === 'skip') {
      onSelectionChange(null);
    } else if (next === 'pick' && selection?.isNew) {
      // Switching from create to pick should clear an in-flight new selection
      onSelectionChange(null);
    } else if (next === 'create' && !selection?.isNew) {
      onSelectionChange(null);
    }
  };

  return (
    <div className="space-y-4">
      <div>
        <h4 className="text-sm font-medium text-gray-900 dark:text-white">Link a Console project</h4>
        <p className="mt-1 text-xs text-gray-500 dark:text-gray-400">
          Tasks generated by <code className="rounded bg-gray-100 px-1 py-0.5 dark:bg-gray-700">/generate-tasks</code> will be pushed to the selected board on{' '}
          <a
            href="https://console.keylinkit.com"
            target="_blank"
            rel="noreferrer"
            className="text-blue-600 hover:underline dark:text-blue-400"
          >
            console.keylinkit.com
          </a>
          . You can skip this and link later by editing <code className="rounded bg-gray-100 px-1 py-0.5 dark:bg-gray-700">.lab/console-project.json</code>.
        </p>
      </div>

      {/* Mode tabs */}
      <div className="inline-flex rounded-md border border-gray-200 p-1 dark:border-gray-700">
        <ModeTab active={mode === 'pick'} onClick={() => switchMode('pick')} disabled={isCreating}>
          Pick existing
        </ModeTab>
        <ModeTab active={mode === 'create'} onClick={() => switchMode('create')} disabled={isCreating}>
          Create new
        </ModeTab>
        <ModeTab active={mode === 'skip'} onClick={handleSkip} disabled={isCreating}>
          Skip
        </ModeTab>
      </div>

      {mode === 'pick' && (
        <div className="space-y-3">
          <Input
            type="text"
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            placeholder="Search Console projects…"
            className="w-full"
            disabled={isCreating}
          />

          {listError && (
            <div className="rounded-md border border-red-200 bg-red-50 p-2 text-xs text-red-700 dark:border-red-900/50 dark:bg-red-900/20 dark:text-red-300">
              {listError}
            </div>
          )}

          <div className="max-h-72 overflow-y-auto rounded-md border border-gray-200 dark:border-gray-700">
            {loadingList && (
              <div className="flex items-center justify-center gap-2 p-4 text-sm text-gray-500 dark:text-gray-400">
                <Loader2 className="h-4 w-4 animate-spin" />
                Loading projects…
              </div>
            )}
            {!loadingList && projects.length === 0 && !listError && (
              <div className="p-4 text-center text-sm text-gray-500 dark:text-gray-400">
                {debouncedSearch ? 'No projects match your search.' : 'No projects yet.'}
              </div>
            )}
            {!loadingList && projects.map((project) => {
              const isSelected = selection?.id === project.id && !selection.isNew;
              return (
                <button
                  key={project.id}
                  type="button"
                  onClick={() => handlePick(project)}
                  disabled={isCreating}
                  className={`block w-full border-b border-gray-100 p-3 text-left transition-colors last:border-b-0 dark:border-gray-700 ${
                    isSelected
                      ? 'bg-blue-50 dark:bg-blue-900/30'
                      : 'hover:bg-gray-50 dark:hover:bg-gray-700/50'
                  }`}
                >
                  <div className="flex items-center justify-between gap-2">
                    <span className="font-medium text-gray-900 dark:text-white">{project.name}</span>
                    <span className="rounded-full bg-gray-100 px-2 py-0.5 text-xs text-gray-600 dark:bg-gray-700 dark:text-gray-300">
                      {project.type}
                    </span>
                  </div>
                  {project.description && (
                    <p className="mt-1 line-clamp-2 text-xs text-gray-500 dark:text-gray-400">
                      {project.description}
                    </p>
                  )}
                </button>
              );
            })}
          </div>

          {selection && !selection.isNew && (
            <SelectionBadge
              label="Linked to"
              name={selectedProject?.name || selection.name}
              onClear={() => onSelectionChange(null)}
              disabled={isCreating}
            />
          )}
        </div>
      )}

      {mode === 'create' && (
        <div className="space-y-3">
          <div>
            <label className="mb-1 block text-sm font-medium text-gray-700 dark:text-gray-300">
              Project name
            </label>
            <Input
              type="text"
              value={newName}
              onChange={(e) => setNewName(e.target.value)}
              placeholder="My new initiative"
              className="w-full"
              disabled={isCreating || creating}
            />
          </div>
          <div>
            <label className="mb-1 block text-sm font-medium text-gray-700 dark:text-gray-300">
              Description (optional)
            </label>
            <textarea
              value={newDescription}
              onChange={(e) => setNewDescription(e.target.value)}
              placeholder="Short summary of what this project covers"
              rows={3}
              disabled={isCreating || creating}
              className="w-full rounded-md border border-gray-300 bg-white px-3 py-2 text-sm text-gray-900 focus:border-blue-500 focus:outline-none focus:ring-1 focus:ring-blue-500 dark:border-gray-600 dark:bg-gray-700 dark:text-white"
            />
            <p className="mt-1 text-xs text-gray-500 dark:text-gray-400">
              Type defaults to <code className="rounded bg-gray-100 px-1 dark:bg-gray-700">dev</code>; change later in Console if needed.
            </p>
          </div>

          {createError && (
            <div className="rounded-md border border-red-200 bg-red-50 p-2 text-xs text-red-700 dark:border-red-900/50 dark:bg-red-900/20 dark:text-red-300">
              {createError}
            </div>
          )}

          {selection?.isNew && (
            <SelectionBadge
              label="Created and linked"
              name={selection.name}
              onClear={() => onSelectionChange(null)}
              disabled={isCreating}
            />
          )}

          {!selection?.isNew && (
            <button
              type="button"
              onClick={handleCreate}
              disabled={isCreating || creating || !newName.trim()}
              className="inline-flex items-center gap-2 rounded-md bg-blue-600 px-4 py-2 text-sm font-medium text-white hover:bg-blue-700 disabled:cursor-not-allowed disabled:opacity-50"
            >
              {creating ? <Loader2 className="h-4 w-4 animate-spin" /> : <Plus className="h-4 w-4" />}
              {creating ? 'Creating…' : 'Create Console project'}
            </button>
          )}
        </div>
      )}

      {mode === 'skip' && (
        <div className="rounded-md border border-gray-200 bg-gray-50 p-3 text-sm text-gray-600 dark:border-gray-700 dark:bg-gray-900/30 dark:text-gray-400">
          No Console project will be linked. <code className="rounded bg-white px-1 dark:bg-gray-700">/push-to-console</code> will tell you to link one before pushing tasks. You can revisit by editing <code className="rounded bg-white px-1 dark:bg-gray-700">.lab/console-project.json</code> in the project root.
        </div>
      )}
    </div>
  );
}

function ModeTab({
  active,
  onClick,
  disabled,
  children,
}: {
  active: boolean;
  onClick: () => void;
  disabled: boolean;
  children: React.ReactNode;
}) {
  return (
    <button
      type="button"
      onClick={onClick}
      disabled={disabled}
      className={`rounded px-3 py-1.5 text-sm font-medium transition-colors ${
        active
          ? 'bg-blue-600 text-white'
          : 'text-gray-700 hover:bg-gray-100 dark:text-gray-300 dark:hover:bg-gray-700'
      } disabled:cursor-not-allowed disabled:opacity-50`}
    >
      {children}
    </button>
  );
}

function SelectionBadge({
  label,
  name,
  onClear,
  disabled,
}: {
  label: string;
  name: string;
  onClear: () => void;
  disabled: boolean;
}) {
  return (
    <div className="flex items-center justify-between gap-2 rounded-md border border-blue-200 bg-blue-50 p-3 dark:border-blue-900/50 dark:bg-blue-900/20">
      <div className="text-sm">
        <span className="text-gray-600 dark:text-gray-400">{label}: </span>
        <span className="font-medium text-gray-900 dark:text-white">{name}</span>
      </div>
      <button
        type="button"
        onClick={onClear}
        disabled={disabled}
        className="rounded p-1 text-gray-400 hover:bg-blue-100 hover:text-gray-600 disabled:cursor-not-allowed dark:hover:bg-blue-900/50"
        title="Clear selection"
      >
        <X className="h-4 w-4" />
      </button>
    </div>
  );
}
